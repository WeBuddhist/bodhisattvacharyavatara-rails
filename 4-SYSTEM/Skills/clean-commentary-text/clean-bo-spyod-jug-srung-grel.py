import re
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# Paths — adjust if running from a different working directory
# ---------------------------------------------------------------------------
VAULT = Path(__file__).resolve().parents[3]   # vault root
SOURCE = VAULT / "1-SOURCES/Commentaries/bo-སྤྱོད་འཇུག་སྒྲུང་འགྲེལ།.md"
OUTPUT = VAULT / "0-INBOX/bo-spyod-jug-srung-grel-clean.md"

# ---------------------------------------------------------------------------
# Lines to remove verbatim (stripped content must match exactly)
# ---------------------------------------------------------------------------
REMOVE_LINES: set[str] = {
    # Running header A (single line)
    "མཁྱེན་བརྩེའི་འོད་སྣང་ལས། སྤྱོད་འཇུག་སྒྲུང་འགྲེལ།",
    # Running header B part 1 (when split across two lines)
    "མཁྱེན་བརྩེའི་འོད་སྣང་ལས།",
    # Running footer
    "སྤྱོད་འཇུག་སྒྲུང་འགྲེལ་ལས་འབྲས་གསལ་བའི་མེ་ལོང་ཞེས་བྱ་བ་བཞུགས།",
}

# When header B is split, part 2 appears on the very next line.
# We handle it as a separate entry so it is caught individually even
# if the two-line pattern breaks mid-file.
REMOVE_LINES.add("སྤྱོད་འཇུག་སྒྲུང་འགྲེལ།")

# ---------------------------------------------------------------------------
# Patterns
# ---------------------------------------------------------------------------
PAGE_MARKER  = re.compile(r'^\s*-\d+-\s*$')
MID_SPACE    = re.compile(r'([ༀ-࿿]) +([ༀ-࿿])')
NBT          = '༌'   # ༌  non-breaking tsheg
STD_TSHEG    = '་'   # ་  standard inter-syllable tsheg

# Sentence / verse endings after which we do NOT join the next line
SENTENCE_END = re.compile(r'[།॥།༎]\s*$')

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def is_verse_line(line: str) -> bool:
    """Verse lines end with ། །  or །།  (shad pairs)."""
    s = line.rstrip()
    return s.endswith('། །') or s.endswith('།།') or s.endswith('། །།')


def remove_mid_spaces(line: str) -> tuple[str, int]:
    """Collapse spaces between Tibetan Unicode characters. Returns (new_line, n_removals)."""
    total = 0
    prev = None
    while prev != line:
        prev = line
        line, n = MID_SPACE.subn(r'\1\2', line)
        total += n
    return line, total


# ---------------------------------------------------------------------------
# Main clean function
# ---------------------------------------------------------------------------

def clean(text: str) -> tuple[str, dict]:
    lines = text.split('\n')
    out: list[str] = []
    stats = {
        'page_markers_removed': 0,
        'header_footer_lines_removed': 0,
        'nbt_replacements': 0,
        'mid_word_spaces_removed': 0,
        'lines_joined': 0,
    }

    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        # 1. Page markers
        if PAGE_MARKER.match(line):
            stats['page_markers_removed'] += 1
            i += 1
            continue

        # 2. Running headers / footers
        if stripped in REMOVE_LINES:
            stats['header_footer_lines_removed'] += 1
            i += 1
            continue

        # 3. Non-breaking tshegs → standard tshegs
        if NBT in line:
            n = line.count(NBT)
            line = line.replace(NBT, STD_TSHEG)
            stats['nbt_replacements'] += n

        # 4. Mid-word spaces (skip verse lines to preserve spacing)
        if not is_verse_line(line):
            line, n = remove_mid_spaces(line)
            stats['mid_word_spaces_removed'] += n

        # 5. Join orphaned line fragments to the previous line.
        #    Condition: current line is non-empty, the last output line is
        #    non-empty, the last output line does NOT end with sentence-closing
        #    punctuation, AND the current line is short (≤ 20 chars stripped).
        if (out
                and stripped
                and len(stripped) <= 20
                and not SENTENCE_END.search(out[-1])
                and not is_verse_line(out[-1])
                and not PAGE_MARKER.match(line)
                and stripped not in REMOVE_LINES):
            out[-1] = out[-1].rstrip() + ' ' + stripped
            stats['lines_joined'] += 1
            i += 1
            continue

        out.append(line)
        i += 1

    # 6. Normalise runs of more than one blank line → single blank line
    result = re.sub(r'\n{3,}', '\n\n', '\n'.join(out))

    return result, stats


# ---------------------------------------------------------------------------
