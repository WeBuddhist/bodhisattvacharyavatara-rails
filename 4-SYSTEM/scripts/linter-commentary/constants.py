def _call_api(url, timeout=10):
    try:
        with urllib.request.urlopen(url, timeout=timeout) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except Exception:
        return None


def _write_languages_file(name_map: dict, code_map: dict):
    """Persist fetched language data to languages.py."""
    lang_file = Path(__file__).parent / "languages.py"
    timestamp = datetime.now(timezone.utc).isoformat()
    lines = [
        "# AUTO-GENERATED by load_languages() — do not edit manually.",
        f"# Last updated: {timestamp}",
        f"LANGUAGE_VALUES = frozenset({{{', '.join(repr(c) for c in sorted(code_map))}}})",
        "LANGUAGE_NAME_MAP = {",
    ]
    for k, v in sorted(name_map.items()):
        lines.append(f"    {k!r}: {v!r},")
    lines.append("}")
    lines.append("LANGUAGE_CODE_TO_NAME = {")
    for k, v in sorted(code_map.items()):
        lines.append(f"    {k!r}: {v!r},")
    lines.append("}")
    content = "\n".join(lines) + "\n"
    lang_file.write_bytes(content.encode("utf-8"))


def load_languages():
    """Fetch language list from API, update runtime globals, persist to languages.py."""
    try:
        data = _call_api(LANGUAGES_API)
        if not isinstance(data, list) or not data:
            raise ValueError("unexpected response")
        name_map, code_map = {}, {}
        for entry in data:
            code = entry.get("code", "").strip()
            name = entry.get("name", "").strip()
            if code and name:
                name_map[name.lower()] = code
                code_map[code] = name
        if not code_map:
            raise ValueError("no valid entries in response")
        # Mutate in place so all importers see the update
        LANGUAGE_VALUES.clear()
        LANGUAGE_VALUES.update(code_map)
        LANGUAGE_NAME_MAP.clear()
        LANGUAGE_NAME_MAP.update(name_map)
        LANGUAGE_CODE_TO_NAME.clear()
        LANGUAGE_CODE_TO_NAME.update(code_map)
        LANG_TAG_MAP.clear()
        LANG_TAG_MAP.update({c: c for c in code_map})
        _write_languages_file(name_map, code_map)
    except Exception:
        # API unreachable — runtime values come from languages.py import
        pass
