# ── File generator ────────────────────────────────────────────────────────────

def blocks_section(file_path, blocks):
    """Return transclusion lines for a list of block IDs, or empty string."""
    if not blocks:
        return ""
    return "\n".join(f"![[{file_path}#{b}]]" for b in blocks)

def disambig_first(file_path, blocks):
    """Return first-block citation for disambiguated verse section."""
    if not blocks:
        return ""
    return f"({file_path}#{blocks[0]})"

def generate_file(verse_num):
    verse_id = f"3-{verse_num}"
    out_path = os.path.join(VERSES_DIR, f"{verse_id}.md")

    if os.path.exists(out_path):
        return "skipped"

    kb = KUNPAL_BLOCKS[verse_num]
    nb = NGULCHU_BLOCKS[verse_num]
    sb = SABZANG_BLOCKS[verse_num]
    pb = PRAJNA_BLOCKS[verse_num]
    sy = SYNTH[verse_num]

    kunpal_passages  = blocks_section(KUNPAL,  kb)
    ngulchu_passages = blocks_section(NGULCHU, nb)
    sabzang_passages = blocks_section(SABZANG, sb)
    prajna_passages  = blocks_section(PRAJNA,  pb)

    # Disambiguated verse citations
    d_kunpal  = disambig_first(KUNPAL,  kb)
    d_ngulchu = disambig_first(NGULCHU, nb)
    d_sabzang = disambig_first(SABZANG, sb)
    d_prajna  = disambig_first(PRAJNA,  pb)
    disambig_citations = "\n".join(
        c for c in [d_kunpal, d_ngulchu, d_sabzang, d_prajna] if c
    )

    content = f"""---
verse_id: {verse_id}
root_text: {TRANS}
root_block: ^{verse_id}
language: bo
commentaries: [kunpal, ngulchu-thogmed, sabzang, prajnakaramati]
status: draft
---

## Verse

![[{TRANS}#^{verse_id}]]

## Commentary passages

### kunpal

{kunpal_passages}

### ngulchu-thogmed

{ngulchu_passages}

### sabzang

{sabzang_passages}

### prajnakaramati

{prajna_passages}

## Synthesis (original language)

### kunpal

{sy["kunpal"]}

### ngulchu-thogmed

{sy["ngulchu"]}

### sabzang

{sy["sabzang"]}

### prajnakaramati

{sy["prajna"]}

### Consensus

{sy["consensus"]}

## Disambiguated verse (original language)

![[{TRANS}#^{verse_id}]]

{disambig_citations}
"""

    os.makedirs(VERSES_DIR, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)
    return "created"

# ── Main ──────────────────────────────────────────────────────────────────────

created = 0
